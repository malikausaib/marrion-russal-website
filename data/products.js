export function getProductById(id) {
  return PRODUCTS.find(p => p.id === id) || null;
}

export function filterProducts({ family = "ALL", query = "", status = "current" }) {
  return PRODUCTS.filter(p => {
    const matchesStatus = !status || p.status === status;
    const matchesFamily = !family || family === "ALL" || p.family.toUpperCase() === family.toUpperCase();
    const matchesQuery = !query || 
      p.name.toLowerCase().includes(query.toLowerCase()) || 
      p.family.toLowerCase().includes(query.toLowerCase()) ||
      p.formulation.toLowerCase().includes(query.toLowerCase());
    return matchesStatus && matchesFamily && matchesQuery;
  });
}
